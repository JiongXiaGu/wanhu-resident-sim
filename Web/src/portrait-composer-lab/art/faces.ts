export function faceArt(look: Look): string {
  const s = skins[look.skinPaletteId];
  // 发色可改变眉色，但换发型/帽子/服饰绝不改变 Face 图层。
  const brow = look.baseHairColorId === 'silver' ? '#777b70' : hairs[look.baseHairColorId].base;
  const ears = p('M88 112Q74 106 77 122Q79 135 90 136Z',s.base,s.line,.8)+p('M170 112Q182 107 180 123Q179 135 168 137Z',s.base,s.line,.8)+l('M81 118Q89 117 85 128M176 117Q170 118 173 128',s.shade,1.3);
  return ears + (look.frame === 'female.adult' ? femaleFaces(s,brow) : maleFaces(s,brow))[look.faceFamilyId];
}
